#!/usr/bin/env node
/**
 * One-time migration helper: dumps the rows of the legacy data/orders.db
 * (better-sqlite3 era) as INSERT statements for D1.
 *
 *   node scripts/export-sqlite-to-sql.js > db/seed.sql
 *   npx wrangler d1 execute womania-db --remote --file db/seed.sql
 */
const Database = require("better-sqlite3");
const path = require("path");

const db = new Database(path.join(__dirname, "..", "data", "orders.db"), {
  readonly: true,
});

const TABLES = [
  "settings",
  "categories",
  "category_subcategories",
  "products",
  "product_images",
  "navigation_items",
  "coupons",
  "site_content",
  "orders",
  "order_items",
];

function literal(value) {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") return Number.isFinite(value) ? String(value) : "NULL";
  if (Buffer.isBuffer(value)) return `X'${value.toString("hex")}'`;
  return `'${String(value).replace(/'/g, "''")}'`;
}

const out = [];
out.push("-- Generated by scripts/export-sqlite-to-sql.js from data/orders.db");
out.push(`-- ${new Date().toISOString()}`);
out.push("PRAGMA foreign_keys = OFF;");

for (const table of TABLES) {
  const rows = db.prepare(`SELECT * FROM ${table}`).all();
  if (!rows.length) continue;
  const columns = Object.keys(rows[0]);
  out.push(`\n-- ${table}: ${rows.length} rows`);
  for (const row of rows) {
    const values = columns.map((c) => literal(row[c])).join(", ");
    out.push(
      `INSERT OR REPLACE INTO ${table} (${columns.join(", ")}) VALUES (${values});`,
    );
  }
}

out.push("\nPRAGMA foreign_keys = ON;");
process.stdout.write(out.join("\n") + "\n");
